# Python adalah bahasa pemrograman berorientasi objek.
# Hampir semua hal di Python adalah sebuah objek, lengkap dengan properti dan metodenya.
# Class (Kelas) ibarat sebuah "cetak biru" (blueprint) atau "pabrik" untuk membuat objek.

# Membuat sebuah Class
# Untuk membuat class, gunakan kata kunci 'class':
class MyClass:
  x = 5

# Membuat sebuah Objek
# Kita dapat menggunakan class bernama MyClass untuk membuat objek:
p1 = MyClass()

# Mencetak nilai 'x' dari objek p1:
print(p1.x) 
# Output: 5