# ==========================================
# PYTHON OOP (Object-Oriented Programming)
# ==========================================

# OOP adalah singkatan dari Object-Oriented Programming (Pemrograman Berorientasi Objek).
# Pemrograman prosedural adalah tentang menulis prosedur atau fungsi yang melakukan operasi pada data.
# Sedangkan OOP adalah tentang membuat "Objek" yang berisi data DAN fungsi sekaligus.

# Keuntungan OOP:
# 1. OOP lebih cepat dan lebih mudah dieksekusi.
# 2. OOP menyediakan struktur yang jelas untuk program.
# 3. OOP membantu menjaga kode Python agar DRY "Don't Repeat Yourself" (Jangan Ulangi Dirimu Sendiri), 
#    sehingga kode lebih mudah dikelola, dimodifikasi, dan di-debug.
# 4. OOP memungkinkan pembuatan aplikasi penuh yang dapat digunakan kembali dengan kode yang lebih sedikit.

